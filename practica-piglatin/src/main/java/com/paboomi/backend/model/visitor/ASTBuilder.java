    @Override
    public ASTNode visitInstructionAssignment(LatinParser.InstructionAssignmentContext ctx) {
        if (ctx.assignment() != null)
            return visit(ctx.assignment());
        if (ctx.readStatement() != null)
            return visit(ctx.readStatement());
        if (ctx.printStatement() != null)
            return visit(ctx.printStatement());
        if (ctx.ifStatement() != null)
            return visit(ctx.ifStatement());
        if (ctx.whileStatement() != null)
            return visit(ctx.whileStatement());
        if (ctx.doWhileStatement() != null)
            return visit(ctx.doWhileStatement());
        if (ctx.forStatement() != null)
            return visit(ctx.forStatement());
        if (ctx.jumpStatement() != null)
            return visit(ctx.jumpStatement());
        if (ctx.returnStatement() != null)
            return visit(ctx.returnStatement());
        if (ctx.expression() != null)
            return visit(ctx.expression());
        return null;
    }

