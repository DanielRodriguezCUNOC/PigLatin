    @Override
    public ASTNode visitDeclaration(LatinParser.DeclarationContext ctx) {
        String id = ctx.ID().getText();
        String type = ctx.type() != null ? extractType(ctx.type()) : null;
        ASTNode initializer = ctx.expression() != null ? visit(ctx.expression()) : null;

        return new NodeVariableDeclaration(
                id,
                type,
                null,
                ctx.getStart().getLine(),
                ctx.getStart().getCharPositionInLine());
    }

    @Override
    public ASTNode visitArrayDeclaration(LatinParser.ArrayDeclarationContext ctx) {
        String id = ctx.ID().getText();
        ASTNode sizeExpr = visit(ctx.expression());
        String elementType = ctx.type() != null ? extractType(ctx.type()) : null;

        NodeArrayDeclaration arrDecl = new NodeArrayDeclaration(
                id,
                sizeExpr,
                elementType,
                new ArrayList<>(),
                ctx.getStart().getLine(),
                ctx.getStart().getCharPositionInLine());

        if (ctx.arrayValues() != null) {
            for (LatinParser.ExpressionContext exprCtx : ctx.arrayValues().expression()) {
                ASTNode value = visit(exprCtx);
                if (value != null) {
                    arrDecl.getInitialValues().add(value);
                }
            }
        }

        return arrDecl;
    }

    @Override
    public ASTNode visitStructDefinition(LatinParser.StructDefinitionContext ctx) {
        String id = ctx.ID().getText();
        NodeStructDefinition structDef = new NodeStructDefinition(
                id,
                new ArrayList<>(),
                ctx.getStart().getLine(),
                ctx.getStart().getCharPositionInLine());

        for (LatinParser.StructFieldDeclarationContext fieldCtx : ctx.structFieldDeclaration()) {
            ASTNode field = visit(fieldCtx);
            if (field != null) {
                structDef.addField(field);
            }
        }

        return structDef;
    }

