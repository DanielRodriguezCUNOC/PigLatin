    @Override
    public ASTNode visitIfStatement(LatinParser.IfStatementContext ctx) {
        ASTNode conditionNode = visit(ctx.booleanExpression());
        NodeBooleanExpression condition = wrapBoolean(conditionNode, ctx.getStart().getLine(),
                ctx.getStart().getCharPositionInLine());
        NodeBlock thenBlock = asBlock(visit(ctx.block()));

        NodeIf nodeIf = new NodeIf(
                condition,
                thenBlock,
                new ArrayList<>(),
                null,
                ctx.getStart().getLine(),
                ctx.getStart().getCharPositionInLine());

        //* else if clauses
        for (LatinParser.ElseIfClauseContext elseIfCtx : ctx.elseIfClause()) {
            ASTNode elseConditionNode = visit(elseIfCtx.booleanExpression());
            NodeBooleanExpression elseCondition = wrapBoolean(elseConditionNode, elseIfCtx.getStart().getLine(),
                    elseIfCtx.getStart().getCharPositionInLine());
            NodeBlock elseIfBlock = asBlock(visit(elseIfCtx.block()));
            nodeIf.addElseIfClause(elseCondition, elseIfBlock);
        }

        //* else clause
        if (ctx.elseClause() != null) {
            nodeIf.setElseBlock(asBlock(visit(ctx.elseClause())));
        }

        return nodeIf;
    }

