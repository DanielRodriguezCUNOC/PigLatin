    // STRUCT LITERALS
    // ============================================================

    @Override
    public ASTNode visitStructLiteral(LatinParser.StructLiteralContext ctx) {
        String typeName = ctx.ID() != null ? ctx.ID().getText() : null;
        NodeStructLiteral structLit = new NodeStructLiteral(
                typeName,
                new ArrayList<>(),
                ctx.getStart().getLine(),
                ctx.getStart().getCharPositionInLine());
        for (LatinParser.StructFieldInitializerContext initCtx : ctx.structFieldInitializer()) {
            ASTNode init = visit(initCtx);
            if (init != null) {
                structLit.addFieldInitializer((NodeStructFieldInitializer) init);
            }
        }
        return structLit;
    }

    @Override
    public ASTNode visitStructFieldInitializer(LatinParser.StructFieldInitializerContext ctx) {
        String fieldName = ctx.ID().getText();
        ASTNode value = visit(ctx.expression());
        return new NodeStructFieldInitializer(
                fieldName,
                value,
                ctx.getStart().getLine(),
                ctx.getStart().getCharPositionInLine());
    }

