    @Override
    public ASTNode visitDoWhileStatement(LatinParser.DoWhileStatementContext ctx) {
        NodeBlock block = asBlock(visit(ctx.block()));
        ASTNode conditionNode = visit(ctx.booleanExpression());
        NodeBooleanExpression condition = wrapBoolean(conditionNode, ctx.getStart().getLine(),
                ctx.getStart().getCharPositionInLine());
        return new NodeDoWhile(
                block,
                condition,
                ctx.getStart().getLine(),
                ctx.getStart().getCharPositionInLine());
    }

    @Override
    public ASTNode visitForStandard(LatinParser.ForStandardContext ctx) {
        ASTNode init = ctx.forInit() != null ? visit(ctx.forInit()) : null;
        ASTNode conditionNode = ctx.forCondition() != null ? visit(ctx.forCondition()) : null;
        NodeBooleanExpression condition = conditionNode != null
                ? wrapBoolean(conditionNode, ctx.getStart().getLine(), ctx.getStart().getCharPositionInLine())
                : null;
        ASTNode update = ctx.forUpdate() != null ? visit(ctx.forUpdate()) : null;
        NodeBlock block = asBlock(visit(ctx.block()));

        return new NodeFor(
                init,
                condition,
                update,
                block,
                ctx.getStart().getLine(),
                ctx.getStart().getCharPositionInLine());
    }

